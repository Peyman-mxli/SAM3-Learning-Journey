"""Build the final environmental validation report from controlled-suite CSVs."""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


LABELS = {
    "baseline": "Baseline",
    "low_light": "Low light",
    "partial_occlusion": "Partial occlusion",
    "motion_blur": "Motion blur",
    "reduced_scale": "Reduced scale",
}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results-dir", default="results/validation")
    parser.add_argument(
        "--output",
        default="docs/ENVIRONMENTAL-VALIDATION-RESULTS.md",
    )
    args = parser.parse_args()

    result_dir = Path(args.results_dir)
    summary = pd.read_csv(result_dir / "condition_summary.csv")
    deltas = pd.read_csv(result_dir / "condition_deltas.csv")

    wanted = [
        "condition",
        "total_observations_delta_vs_baseline",
        "unique_trackers_delta_vs_baseline",
        "average_confidence_delta_vs_baseline",
        "average_track_length_delta_vs_baseline",
    ]
    merged = summary.merge(deltas[wanted], on="condition", how="left")

    rows = []
    for _, r in merged.iterrows():
        rows.append(
            "| {condition} | {obs} | {tracks} | {conf:.4f} | {length:.4f} | "
            "{dobs:+.0f} | {dtracks:+.0f} | {dconf:+.4f} |".format(
                condition=LABELS.get(r["condition"], r["condition"]),
                obs=int(r["total_observations"]),
                tracks=int(r["unique_trackers"]),
                conf=float(r["average_confidence"]),
                length=float(r["average_track_length"]),
                dobs=float(r["total_observations_delta_vs_baseline"]),
                dtracks=float(r["unique_trackers_delta_vs_baseline"]),
                dconf=float(r["average_confidence_delta_vs_baseline"]),
            )
        )

    non_baseline = merged[merged["condition"] != "baseline"].copy()
    worst_conf = non_baseline.loc[non_baseline["average_confidence"].idxmin()]
    shortest = non_baseline.loc[non_baseline["average_track_length"].idxmin()]

    report = """# Environmental Validation Results — Project 13

This report was generated from the controlled five-video validation suite for
**Run 45ef3e05**.

## Research question

> How do variations in lighting and occlusion affect the precision and
> stability of object tracking in recorded videos?

## Experimental design

The same recorded source video is used for every condition so scene content
remains constant while one visual perturbation is introduced.

Conditions:

1. Baseline
2. Low light
3. Partial occlusion
4. Motion blur
5. Reduced scale

The same YOLO model, confidence threshold, Supervision representation, and
ByteTrack configuration are used across all sessions.

## Results

| Condition | Observations | Unique trackers | Avg confidence | Avg track length | Δ observations | Δ trackers | Δ confidence |
|---|---:|---:|---:|---:|---:|---:|---:|
{rows}

## Interpretation

The lowest average detection confidence among perturbed conditions was
**{worst_condition}**, with an average confidence of **{worst_conf:.4f}**.

The shortest average track length among perturbed conditions was
**{short_condition}**, with **{short_length:.4f} observations per tracker**.

Changes in tracker count and average track length are useful indicators of
temporal instability and possible fragmentation under degraded visual
conditions.

## Evidence boundary

These are controlled **robustness indicators**, not full ground-truth tracking
accuracy. True ID-switch and fragmentation accuracy still require
human-reviewed temporal identities. Mask IoU and Dice require human-reviewed
segmentation masks.

## Reproducibility

Generated by:

- \`evaluation/create_condition_variants.py\`
- \`evaluation/run_validation_suite.py\`
- \`evaluation/analyze_validation_conditions.py\`
- \`evaluation/build_validation_report.py\`

Machine-readable outputs are preserved in \`results/validation/\`.
""".format(
        rows="\n".join(rows),
        worst_condition=LABELS.get(worst_conf["condition"], worst_conf["condition"]),
        worst_conf=float(worst_conf["average_confidence"]),
        short_condition=LABELS.get(shortest["condition"], shortest["condition"]),
        short_length=float(shortest["average_track_length"]),
    )

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(report, encoding="utf-8")
    print(f"Saved {output}")


if __name__ == "__main__":
    main()
