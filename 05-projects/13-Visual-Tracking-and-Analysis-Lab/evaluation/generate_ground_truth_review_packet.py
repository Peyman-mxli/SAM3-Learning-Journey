"""Generate a human-review packet from a Project 13 video and predictions.

The packet intentionally separates *candidate annotations* from ground truth.
It exports selected frames, YOLO/ByteTrack candidate boxes, and blank review
columns. A person can then correct IDs/boxes and optionally draw segmentation
masks with the companion Streamlit review app.

Nothing generated by this script is called ground truth until it is reviewed.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import cv2
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from ultralytics import YOLO
import supervision as sv


COLUMNS = [
    "frame_index",
    "candidate_track_id",
    "review_track_id",
    "class_name",
    "x1",
    "y1",
    "x2",
    "y2",
    "confidence",
    "reviewed",
    "keep",
    "notes",
]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("video")
    parser.add_argument("--output-dir", default="evaluation/review_packet")
    parser.add_argument("--model", default="yolov8n.pt")
    parser.add_argument("--confidence", type=float, default=0.35)
    parser.add_argument("--every", type=int, default=5)
    parser.add_argument("--max-frames", type=int, default=25)
    args = parser.parse_args()

    video = Path(args.video)
    out = Path(args.output_dir)
    frames_dir = out / "frames"
    frames_dir.mkdir(parents=True, exist_ok=True)

    model = YOLO(args.model)
    tracker = sv.ByteTrack()

    cap = cv2.VideoCapture(str(video))
    if not cap.isOpened():
        raise RuntimeError(f"Could not open {video}")

    rows = []
    frame_index = 0
    selected = 0

    while selected < args.max_frames:
        ok, frame = cap.read()
        if not ok:
            break

        result = model(frame, verbose=False)[0]
        detections = sv.Detections.from_ultralytics(result)

        if len(detections):
            detections = detections[detections.confidence >= args.confidence]
            detections = tracker.update_with_detections(detections)

        if frame_index % args.every == 0:
            frame_name = f"frame_{frame_index:04d}.jpg"
            cv2.imwrite(str(frames_dir / frame_name), frame)
            selected += 1

            for i in range(len(detections)):
                x1, y1, x2, y2 = [float(v) for v in detections.xyxy[i]]
                class_id = int(detections.class_id[i])
                track_id = (
                    int(detections.tracker_id[i])
                    if detections.tracker_id is not None
                    else -1
                )
                confidence = float(detections.confidence[i])
                rows.append(
                    {
                        "frame_index": frame_index,
                        "candidate_track_id": track_id,
                        "review_track_id": track_id,
                        "class_name": model.names[class_id],
                        "x1": round(x1, 2),
                        "y1": round(y1, 2),
                        "x2": round(x2, 2),
                        "y2": round(y2, 2),
                        "confidence": round(confidence, 6),
                        "reviewed": False,
                        "keep": True,
                        "notes": "",
                    }
                )

        frame_index += 1

    cap.release()

    packet = pd.DataFrame(rows, columns=COLUMNS)
    packet.to_csv(out / "tracking_review.csv", index=False)

    manifest = pd.DataFrame(
        {
            "frame_index": sorted(packet["frame_index"].unique())
            if not packet.empty
            else [],
        }
    )
    manifest["frame_file"] = manifest["frame_index"].map(
        lambda i: f"frames/frame_{int(i):04d}.jpg"
    )
    manifest["reviewed"] = False
    manifest["notes"] = ""
    manifest.to_csv(out / "frame_manifest.csv", index=False)

    print(f"Saved review packet to: {out}")
    print(f"Selected frames: {selected}")
    print(f"Candidate detections: {len(packet)}")
    print("IMPORTANT: candidate annotations are NOT ground truth until reviewed.")


if __name__ == "__main__":
    main()
