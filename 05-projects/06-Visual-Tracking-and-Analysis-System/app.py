@st.cache_data
def load_csv(path: Path) -> pd.DataFrame:
    """
    Load a CSV report.
    """

    if not path.exists():
        return pd.DataFrame()

    return pd.read_csv(path)


@st.cache_data
def load_markdown(path: Path) -> str:
    """
    Load a Markdown documentation file.
    """

    if not path.exists():
        return ""

    return path.read_text(
        encoding="utf-8"
    )


