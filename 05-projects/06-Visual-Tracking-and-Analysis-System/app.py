def metric_value(
    metric_name: str,
    default: str = "N/A",
) -> str:
    """
    Retrieve a metric from performance_summary.csv.
    """

    if performance_df.empty:
        return default

    if "metric" not in performance_df.columns:
        return default

    if "value" not in performance_df.columns:
        return default

    match = performance_df[
        performance_df["metric"] == metric_name
    ]

    if match.empty:
        return default

    return str(
        match.iloc[0]["value"]
    )


def show_image(
    image_path: Path,
    caption: str,
) -> None:
    """
    Display a report image if it exists.
    """

    if image_path.exists():

        st.image(
            str(image_path),
            caption=caption,
            use_container_width=True,
        )

    else:

        st.warning(
            f"Missing visualization: {image_path.name}"
        )


def download_csv_button(
    label: str,
    dataframe: pd.DataFrame,
    filename: str,
    key: str,
) -> None:
    """
    Create a CSV download button.
    """

    if dataframe.empty:
        return

    csv_data = dataframe.to_csv(
        index=False
    ).encode("utf-8")

    st.download_button(
        label=label,
        data=csv_data,
        file_name=filename,
        mime="text/csv",
        key=key,
    )


